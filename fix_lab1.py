import re, sys
sys.stdout.reconfigure(encoding='utf-8')

with open('lab_in_out.tex', 'r', encoding='utf-8') as f:
    text = f.read()

orig_text = text

# 1. тризначне / чотиризначне / шестизначне -> трицифрове / чотирицифрове / шестицифрове
text = re.sub(r'тризначн([а-я]+)', r'трицифров\1', text)
text = re.sub(r'Тризначн([а-я]+)', r'Трицифров\1', text)
text = re.sub(r'чотиризначн([а-я]+)', r'чотирицифров\1', text)
text = re.sub(r'Чотиризначн([а-я]+)', r'Чотирицифров\1', text)
text = re.sub(r'шестизначн([а-я]+)', r'шестицифров\1', text)
text = re.sub(r'Шестизначн([а-я]+)', r'Шестицифров\1', text)

# 2. запитує користувача -> запитує в користувача
text = text.replace('яка запитує користувача дату народження', 'яка запитує в користувача дату народження')
text = text.replace('яка запитує користувача ім\'я його улюбленого мультиплікаційного героя', 'яка запитує в користувача ім\'я його улюбленого мультиплікаційного героя')
text = text.replace('яка запитує користувача назва улюбленого мультфільму', 'яка запитує в користувача назву улюбленого мультфільму')
text = text.replace('яка запитує користувача ім\'я його улюбленого кіногероя', 'яка запитує в користувача ім\'я його улюбленого кіногероя')

# 3. із стороною -> зі стороною, із нього -> з нього
text = text.replace('із стороною $k$ можна вирізати із нього?', 'зі стороною $k$ можна вирізати з нього?')

# 4. \ verb | -> \verb|
text = text.replace(r'\ verb | Я люблю ... |', r'\verb|Я люблю ...|')

# 5. Дана довжина -> Дано довжину, Дане чотирицифрове -> Дано чотирицифрове, Дані деякі дійсні числа -> Дано деякі дійсні числа
text = text.replace('Дана довжина ребра куба.', 'Дано довжину ребра куба.')
text = text.replace('Дане чотирицифрове натуральне число.', 'Дано чотирицифрове натуральне число.')
text = text.replace('Дані деякі дійсні числа', 'Дано деякі дійсні числа')
text = text.replace('Дані катети прямокутного трикутника.', 'Дано катети прямокутного трикутника.')

# 6. приписали її наприкінці -> дописали її в кінці
text = text.replace('приписали її наприкінці.', 'дописали її в кінці.')

# 7. по заданим -> за заданими
text = text.replace('по заданим зовнішнім та внутрішнім радіусам.', 'за заданими зовнішнім та внутрішнім радіусами.')

# 8. до кінця числа -> в кінець числа
text = text.replace('Переставити першу цифру до кінця числа.', 'Переставити першу цифру в кінець числа.')

# 9. ВНЗ, в якій -> ЗВО, в якому; вузі -> виші
text = text.replace('назву ВНЗ, в якій він навчається', 'назву ЗВО, в якому він навчається')
text = text.replace(r'У якому вузі Ви навчаєтеся?', r'У якому виші Ви навчаєтеся?')

# 10. Пробіжка кругів -> кіл
text = text.replace('спортсмен, що "намотав" кругів навколо цього поля? Число $n$ задається з клавіатури.', 'спортсмен, що пробіг $n$ кіл навколо цього поля? Число $n$ задається з клавіатури.')

# 11. число, що виходить при прочитанні / перестановці
text = text.replace('число, що виходить при прочитанні вихідного числа праворуч наліво.', 'число, утворене внаслідок читання початкового числа справа наліво.')
text = text.replace('число, що виходить при перестановці другої та третьої цифр вихідного числа.', 'число, утворене внаслідок перестановки другої та третьої цифр початкового числа.')
text = text.replace('число, що виходить при перестановці першої та другої цифр вихідного числа.', 'число, утворене внаслідок перестановки першої та другої цифр початкового числа.')

# 12. Перевести це значення на радіани -> у радіани
text = text.replace('Перевести це значення на радіани.', 'Перевести це значення в радіани.')

# 13. значення віразу -> значення виразу
text = text.replace('Визначити значення віразу', 'Визначити значення виразу')

# 14. \ footnote { -> \footnote{, вихідне значення -> початкове значення
text = text.replace(r'\ footnote {Для перерахунку за шкалою Фаренгейта необхідно вихідне значення температури', r'\footnote{Для перерахунку за шкалою Фаренгейта необхідно початкове значення температури')

# 15. Маніла виноска
text = text.replace(
    r'Визначити щільність населення в цьому місті Станом на липень 2018 року містом з найбільшою щільністю населення є Маніла "--- столиця держави Філіппіни (43\,079 осіб на км$^2$).}.',
    r'Визначити густоту населення в цьому місті\footnote{Станом на липень 2018 року містом із найбільшою густотою населення є Маніла "--- столиця держави Філіппіни (43\,079 осіб на км$^2$).}.'
)

# 16. Твір цифр -> Добуток цифр
text = text.replace(r'\item \textbf{Твір цифр.}', r'\item \textbf{Добуток цифр.}')

# 17. на листку в клітинку -> на аркуші в клітинку
text = text.replace('на листку в клітинку накрити', 'на аркуші в клітинку накрити')

# 18. << намотати >> -> <<намотати>>
text = text.replace('<< намотати >>', '<<намотати>>')

# 19. Яка відстань (в метрах) зазвичай пробігає -> Яку відстань (у метрах) зазвичай пробігає
text = text.replace('Яка відстань (в метрах) зазвичай пробігає вранці місіс Гамільтон', 'Яку відстань (у метрах) зазвичай пробігає вранці місіс Гамільтон')

# 20. Кількість n вводиться -> Число n вводиться
text = text.replace('Кількість $n$ вводиться з клавіатури.', 'Число $n$ вводиться з клавіатури.')

# 21. Переставити останню цифру на початку числа -> на початок числа
text = text.replace('Переставити останню цифру на початку числа.', 'Переставити останню цифру на початок числа.')

with open('lab_in_out.tex', 'w', encoding='utf-8') as f:
    f.write(text)

print('lab_in_out.tex updated successfully.')

